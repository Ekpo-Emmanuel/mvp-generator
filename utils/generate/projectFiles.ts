function globalsCss(config: ProjectConfig) {
  const bootstrap =
    config.styling === "bootstrap"
      ? '@import url("https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/css/bootstrap.min.css");\n\n'
      : "";

  if (usesTailwind(config)) {
    return trimFile(`
${bootstrap}@tailwind base;
@tailwind components;
@tailwind utilities;

body {
  font-family: Arial, Helvetica, sans-serif;
}
`);
  }

  return trimFile(`
${bootstrap}* {
  box-sizing: border-box;
}

html, body {
  margin: 0;
  min-height: 100%;
  font-family: Arial, Helvetica, sans-serif;
}
`);
}

