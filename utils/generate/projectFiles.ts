export function generateProjectFileMap(config: ProjectConfig): Record<string, string> {
  const authSetup = getAuthSetup(config.auth, config.framework);
  const files: Record<string, string> = {
    "package.json": JSON.stringify(generatePackageJson(config), null, 2) + "\n",
    "README.md": readme(config),
  };

  if (isNextApp(config)) {
    Object.assign(files, nextBaseFiles(config));
  } else if (isRemix(config.framework)) {
    Object.assign(files, remixFiles(config));
  } else {
    Object.assign(files, viteFiles(config));
  }

  if (usesTailwind(config) && isSpa(config.framework)) {
    files["tailwind.config.ts"] = trimFile(`
import type { Config } from "tailwindcss";

export default {
  content: ["./index.html", "./src/**/*.{js,ts,jsx,tsx}"],
  theme: { extend: {} },
  plugins: [],
} satisfies Config;
`);
    files["postcss.config.mjs"] = trimFile(`
export default {
  plugins: {
    tailwindcss: {},
    autoprefixer: {},
  },
};
`);
  }

  const keepBase = new Set(["app/globals.css", "app/layout.tsx", "app/styles.css", "src/index.css"]);
  Object.entries(authSetup.files).forEach(([path, content]) => {
    if (keepBase.has(path) && files[path]) return;
    files[path] = content.endsWith("\n") ? content : content + "\n";
  });

  Object.assign(files, databaseFiles(config));

  const env = {
    ...authSetup.env,
    ...databaseEnv(config),
  };
  const envBody = Object.keys(env).length
    ? Object.entries(env)
        .map(([key, value]) => `${key}=${value}`)
        .join("\n") + "\n"
    : "# No secrets required for this stack\n";
  files[".env.example"] = envBody;

  return files;
}
