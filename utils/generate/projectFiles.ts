function usesTailwind(config: ProjectConfig) {
  return usesTailwindStyle(config.styling);
}

function isNextApp(config: ProjectConfig) {
  return isNext(config.framework);
}

function nextLayout(config: ProjectConfig) {
  const clerk = config.auth === "clerk";
  const auth0 = config.auth === "auth0";

  const imports = [
    'import type { Metadata } from "next";',
    'import { Inter } from "next/font/google";',
    'import "./globals.css";',
    clerk ? 'import { ClerkProvider } from "@clerk/nextjs";' : "",
    auth0 ? 'import { Providers } from "./providers";' : "",
  ]
    .filter(Boolean)
    .join("\n");

  const inner = `{children}`;
  const withAuth0 = auth0 ? `<Providers>${inner}</Providers>` : inner;
  const withClerk = clerk ? `<ClerkProvider>${withAuth0}</ClerkProvider>` : withAuth0;

  return trimFile(`
${imports}

const inter = Inter({ subsets: ["latin"] });

export const metadata: Metadata = {
  title: "Generated App",
  description: "Generated by MVP Generator",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <body className={inter.className}>
        ${withClerk}
      </body>
    </html>
  );
}
`);
}

